#!/bin/bash
# Walter Autonomous Research Runner
# Executes research tasks when Roger is idle

SCRIPT_DIR="/Users/roger/.openclaw/workspace/scripts"
STATE_DIR="/Users/roger/.openclaw/workspace/state"
OUTPUT_DIR="/Users/roger/.openclaw/workspace/output"
MONITOR="$SCRIPT_DIR/walter-coordination-monitor.sh"

get_timestamp() {
    date -u +"%Y-%m-%dT%H:%M:%SZ"
}

get_date_stamp() {
    date +"%Y%m%d"
}

log() {
    echo "[$(date +%H:%M:%S)] $1"
}

mkdir -p "$OUTPUT_DIR/research"
mkdir -p "$OUTPUT_DIR/logs"
log "Initialized autonomous research system"

# Check if Roger is idle
idle_status=$($MONITOR status 2>/dev/null)
idle_state=$(echo "$idle_status" | cut -d: -f1)

if [[ "$idle_state" != "idle" ]]; then
    log "Roger is active. Skipping autonomous research."
    exit 0
fi
log "Roger is idle. Starting autonomous research..."

# Get next task
task_json=$(jq -r '[.autonomousQueue[] | select(.status == "queued")] | sort_by(.priority) | sort_by(.timestamp) | .[0] | @json' "$STATE_DIR/walter-coordination-log.json" 2>/dev/null || echo "")

if [[ -z "$task_json" || "$task_json" == "null" || "$task_json" == "No tasks queued" || "$task_json" == "" ]]; then
    log "No valid tasks found"
    exit 0
fi

task_id=$(echo "$task_json" | jq -r ".id")
task_type=$(echo "$task_json" | jq -r ".type")
task_desc=$(echo "$task_json" | jq -r ".description")
task_target=$(echo "$task_json" | jq -r ".target // \"\"")

log "Starting task: $task_id"
log "Type: $task_type"
log "Description: $task_desc"

# Mark task started
$MONITOR start-task "$task_id" 2>/dev/null

# Create gap analysis output
output_file="$OUTPUT_DIR/research/gap-analysis-$(get_date_stamp)-$(echo $task_id | cut -d- -f2).md"

cat > "$output_file" << 'REPORT'
# Gap Analysis: ERC-8004 agent identity registry on Base Sepolia - deployment path and ecosystem fit

