# Replace timestamp
sed -i '' "s/REPORT_TIMESTAMP/$(get_timestamp)/g" "$output_file" 2>/dev/null || sed -i "s/REPORT_TIMESTAMP/$(get_timestamp)/g" "$output_file"

log "Created gap analysis: $output_file"

# Mark task completed
$MONITOR complete-task "$task_id" "$output_file" 2>/dev/null

log "Autonomous research completed"
echo "  Output: $output_file"

# Create handoff summary
handoff_file="$STATE_DIR/walter-handoff-research-$(get_date_stamp).json"
cat > "$handoff_file" << HANDOFF
{
  "timestamp": "$(get_timestamp)",
  "type": "autonomous_research",
  "taskId": "$task_id",
  "taskType": "$task_type",
  "description": "$task_desc",
  "outputFile": "$output_file",
  "executedWhileRogerIdle": true,
  "requiresResponse": false,
  "summary": "Completed $task_type research: $task_desc",
  "forRoger": "Review output file for findings and recommendations"
}
HANDOFF

log "Created handoff: $handoff_file"
log "Ready for Roger review when he returns"
